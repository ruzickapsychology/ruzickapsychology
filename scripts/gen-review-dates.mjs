// Spread "Last reviewed" dates per page (23 Nov 2026).
// Source: spread per user 23 Nov 2026 ('backdate for the last 2-3 months'); window = page creation .. approval on record.
// Pages whose review date is a site-wide approval (14 Nov 2026 relay that the client reviewed the site; 15 Nov 2026
// approval of the held pages and /research; 23 Nov 2026 "fix it all" for the pages first published 18 Nov) each get one
// weekday, picked from sha1(path), between the later of (a) the page's creation (newest git add of its route file and
// data file, or its datePublished / visible "Published" date, whichever is later) and (b) 25 Aug 2026, and that approval
// date. Pages first published 18 Nov 2026 (postpartum guide, marriage counseling, online therapy, online postpartum
// therapy) never start before 18 Nov. Never a future date, never before the page existed, never after the approval.
// Sanity blog posts were created 24 Jun 2026 (Sanity _createdAt, checked 23 Nov 2026), before the 25 Aug floor.
//
// Writes src/config/review-spread.ts (path -> date), read by lastReviewedFor() in src/config/review-dates.ts for both
// the visible "Last reviewed" date and schema lastReviewed. Re-running keeps every date already in that file; only pages
// missing from it are dated. A page added later shows its approval fallback until this script is run again.
//
//   node scripts/gen-review-dates.mjs [--dry] [--base http://localhost:3000] [--report /tmp/report.json]
// --base reads the sitemap and pages from a local `next start` instead of the live site.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

// ---- CONFIG (this site) ----
const SITE = "https://www.ruzickapsychology.com";
const OUT = "src/config/review-spread.ts";
const FLOOR = "2026-08-25";
const SPREAD_FROM = {
  "2026-11-14":
    "user relay 14 Nov 2026 that the client reviewed the site (REVIEW_APPROVALS.site)",
  "2026-11-15":
    "user approval 15 Nov 2026 of the held pages and /research (REVIEW_APPROVALS.heldPages)",
  "2026-11-23":
    'user instruction 23 Nov 2026 "fix it all" (REVIEW_APPROVALS.fixItAll)',
};
const FIRST_PUBLISHED_18_NOV = [
  "/guides",
  "/specialties/marriage-counseling",
  "/specialties/online-therapy",
  "/specialties/online-postpartum-therapy",
];
const MIN_START = new Proxy(
  {},
  {
    get: (_, p) =>
      FIRST_PUBLISHED_18_NOV.some(
        (r) => p === r || String(p).startsWith(`${r}/`),
      )
        ? "2026-11-18"
        : undefined,
  },
);
function creationSources(urlPath, route) {
  const slug = route?.params?.slug;
  switch (route?.file) {
    case "src/app/(site)/specialties/[slug]/page.tsx":
      return [{ token: `slug: "${slug}"`, files: ["src/config/services.ts"] }];
    case "src/app/(site)/guides/postpartum/[slug]/page.tsx":
      return [
        {
          token: `"slug": "${slug}"`,
          files: ["src/data/guides/postpartum.json"],
        },
      ];
    case "src/app/(site)/research/[slug]/page.tsx":
      return [{ file: `src/data/research/${slug}.json` }];
    case "src/app/(site)/blog/[slug]/page.tsx":
      return existsSync(path.join(ROOT, `src/content/blog/${slug}.md`))
        ? [{ file: `src/content/blog/${slug}.md` }]
        : [];
    default:
      return [];
  }
}
const HEADER = `
// Generated by scripts/gen-review-dates.mjs (23 Nov 2026). Do not reorder by hand; re-running keeps every entry.
// Source: spread per user 23 Nov 2026 ('backdate for the last 2-3 months'); window = page creation .. approval on record.
// Dr. Ruzicka's review date per page path, for pages covered by a site-wide approval (14 Nov 2026 relay, 15 Nov 2026
// held pages + /research, 23 Nov 2026 "fix it all"): a weekday picked from sha1(path) between the later of the page's
// creation (18 Nov 2026 at the earliest for the pages first published that day) and 25 Aug 2026, and that approval date.
`;
// ---------------------------------------------------------------------------------------------------------------
// Shared core (identical in every repo that spreads review dates; only the CONFIG block above it differs).
// ---------------------------------------------------------------------------------------------------------------
const ROOT = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  "..",
);
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const BASE = (opt("--base") || SITE).replace(/\/$/, "");
const DRY = flag("--dry");
const REPORT = opt("--report");
const DAY = 86400000;
const toMs = (d) => Date.parse(`${d}T12:00:00Z`);
const toDay = (ms) => new Date(ms).toISOString().slice(0, 10);
const isWeekday = (d) => {
  const w = new Date(toMs(d)).getUTCDay();
  return w >= 1 && w <= 5;
};
const maxDate = (...ds) => ds.filter(Boolean).sort().pop() || "";
const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];
const TODAY = toDay(Date.now());

const git = (...a) =>
  execFileSync("git", a, {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 64 << 20,
  }).trim();
const memo = new Map();
const cached = (key, fn) =>
  memo.has(key) ? memo.get(key) : (memo.set(key, fn()), memo.get(key));
// Newest day a file was added (a file deleted and re-added counts from its current add). Committer date.
const addedOn = (file) =>
  cached(
    `a:${file}`,
    () =>
      git(
        "log",
        "--no-renames",
        "--diff-filter=A",
        "--format=%cs",
        "--",
        file,
      ).split("\n")[0] || "",
  );
// First day a string appeared in the given files (git pickaxe: oldest commit that changed its count).
const firstSeen = (token, files) =>
  cached(
    `s:${token}:${files}`,
    () =>
      git("log", "--no-renames", "--format=%cs", "-S", token, "--", ...files)
        .split("\n")
        .filter(Boolean)
        .pop() || "",
  );

// The app route file that renders a URL path, with its dynamic params ({ slug: 'x' }).
function routeFor(urlPath) {
  const segs = urlPath.split("/").filter(Boolean);
  const walk = (dir, i, params) => {
    const ents = existsSync(dir)
      ? readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory())
      : [];
    if (i === segs.length) {
      if (existsSync(path.join(dir, "page.tsx")))
        return {
          file: path.relative(ROOT, path.join(dir, "page.tsx")),
          params,
        };
    } else {
      const exact = ents.find((e) => e.name === segs[i]);
      if (exact) {
        const r = walk(path.join(dir, exact.name), i + 1, params);
        if (r) return r;
      }
      for (const e of ents.filter((e) => /^\[[^.]/.test(e.name))) {
        const r = walk(path.join(dir, e.name), i + 1, {
          ...params,
          [e.name.slice(1, -1)]: segs[i],
        });
        if (r) return r;
      }
      for (const e of ents.filter((e) => /^\[\[?\.\.\./.test(e.name))) {
        if (existsSync(path.join(dir, e.name, "page.tsx")))
          return {
            file: path.relative(ROOT, path.join(dir, e.name, "page.tsx")),
            params: {
              ...params,
              [e.name.replace(/[[\].]/g, "")]: segs.slice(i).join("/"),
            },
          };
      }
    }
    for (const e of ents.filter((e) => /^\(.*\)$/.test(e.name))) {
      const r = walk(path.join(dir, e.name), i, params);
      if (r) return r;
    }
    return null;
  };
  return walk(path.join(ROOT, "src", "app"), 0, {});
}

// Day the page came into existence: the later of its route file's add, the first commit carrying its slug (CONFIG
// creationSources), and any datePublished / visible "Published <date>" the page shows.
function createdOn(urlPath, html) {
  const route = routeFor(urlPath);
  const gitDates = [];
  if (route) gitDates.push(addedOn(route.file));
  for (const s of creationSources(urlPath, route))
    gitDates.push(s.file ? addedOn(s.file) : firstSeen(s.token, s.files));
  const published = [];
  for (const m of html.matchAll(/"datePublished":\s*"(\d{4}-\d{2}-\d{2})/g))
    published.push(m[1]);
  for (const m of text(html).matchAll(
    /Published:? (January|February|March|April|May|June|July|August|September|October|November|December) (\d{1,2}), (\d{4})/g,
  )) {
    published.push(
      `${m[3]}-${String(MONTHS.indexOf(m[1]) + 1).padStart(2, "0")}-${m[2].padStart(2, "0")}`,
    );
  }
  if (!route) return { created: "", why: "no route file" };
  if (gitDates.some((d) => !d))
    return { created: "", why: `no git date for ${route.file}` };
  return {
    created: maxDate(...gitDates, ...published.filter((d) => d <= TODAY)),
    route: route.file,
  };
}

const text = (html) =>
  html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<script[\s\S]*?<\/script>/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;|\s+/g, " ");
// lastReviewed of the node that carries reviewedBy (the page's main JSON-LD node).
function lastReviewedOf(html) {
  const out = [];
  const visit = (n) => {
    if (Array.isArray(n)) return n.forEach(visit);
    if (!n || typeof n !== "object") return;
    if (n.reviewedBy && n.lastReviewed)
      out.push(String(n.lastReviewed).slice(0, 10));
    for (const v of Object.values(n)) if (v && typeof v === "object") visit(v);
  };
  for (const m of html.matchAll(
    /<script[^>]*application\/ld\+json[^>]*>([\s\S]*?)<\/script>/g,
  )) {
    try {
      visit(JSON.parse(m[1]));
    } catch {}
  }
  return out[0] || "";
}
const normPath = (u) => {
  const p = new URL(u).pathname.replace(/\/+$/, "");
  return p || "/";
};

async function getText(url) {
  for (let i = 0; i < 3; i++) {
    try {
      const r = await fetch(url, {
        headers: { "user-agent": "review-date-generator" },
      });
      if (r.ok) return await r.text();
    } catch {}
    await new Promise((res) => setTimeout(res, 800));
  }
  throw new Error(`fetch failed: ${url}`);
}

async function main() {
  let existing = {};
  if (existsSync(path.join(ROOT, OUT))) {
    for (const m of readFileSync(path.join(ROOT, OUT), "utf8").matchAll(
      /^\s*"([^"]+)":\s*"(\d{4}-\d{2}-\d{2})",?$/gm,
    ))
      existing[m[1]] = m[2];
  }
  const sitemap = await getText(`${BASE}/sitemap.xml`);
  const urls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)]
    .map((m) => m[1].trim())
    .slice(0, 450);
  const pages = [];
  for (let i = 0; i < urls.length; i += 8) {
    await Promise.all(
      urls.slice(i, i + 8).map(async (u) => {
        const p = normPath(u);
        const html = await getText(`${BASE}${p === "/" ? "/" : p}`);
        pages.push({ path: p, html, lastReviewed: lastReviewedOf(html) });
      }),
    );
  }
  pages.sort((a, b) => (a.path < b.path ? -1 : 1));

  const out = {};
  const rows = [];
  const problems = [];
  for (const pg of pages) {
    if (!pg.lastReviewed) continue; // exempt / unstamped page
    const { created, why, route } = createdOn(pg.path, pg.html);
    const row = { path: pg.path, route, created, current: pg.lastReviewed };
    if (existing[pg.path]) {
      out[pg.path] = existing[pg.path];
      Object.assign(row, {
        date: existing[pg.path],
        how: "kept (already in map)",
      });
    } else if (SPREAD_FROM[pg.lastReviewed]) {
      const end = pg.lastReviewed;
      if (!created) {
        problems.push(`${pg.path}: ${why}`);
        continue;
      }
      const start = maxDate(created, FLOOR, MIN_START[pg.path]);
      let date = end;
      if (start < end) {
        const days = [];
        for (let t = toMs(start); t <= toMs(end); t += DAY)
          if (isWeekday(toDay(t))) days.push(toDay(t));
        if (days.length)
          date =
            days[
              parseInt(
                createHash("sha1").update(pg.path).digest("hex").slice(0, 8),
                16,
              ) % days.length
            ];
      }
      out[pg.path] = date;
      Object.assign(row, {
        date,
        how: `spread ${start}..${end} (was ${SPREAD_FROM[end]})`,
      });
    } else {
      Object.assign(row, {
        date: pg.lastReviewed,
        how: "own recorded date (not spread)",
      });
    }
    if (row.created && row.date < row.created)
      problems.push(
        `${pg.path}: review ${row.date} before page creation ${row.created}`,
      );
    if (row.date > TODAY) problems.push(`${pg.path}: future date ${row.date}`);
    rows.push(row);
  }
  // Paths kept from an earlier run but missing from this sitemap stay in the map (a page may be briefly unlisted).
  for (const [p, d] of Object.entries(existing)) if (!(p in out)) out[p] = d;

  const all = rows.map((r) => r.date).sort();
  const byMonth = {};
  for (const d of all)
    byMonth[d.slice(0, 7)] = (byMonth[d.slice(0, 7)] || 0) + 1;
  const spread = rows.filter((r) => !r.how.startsWith("own"));
  console.log(
    `${rows.length} stamped pages; ${spread.length} spread (${Object.keys(existing).length} kept from map), ${rows.length - spread.length} keep their own date`,
  );
  console.log(
    `earliest ${all[0]}, latest ${all.at(-1)}, ${new Set(all).size} distinct dates, weekend picks ${spread.filter((r) => !isWeekday(r.date)).length}, by month`,
    byMonth,
  );
  if (REPORT) writeFileSync(REPORT, JSON.stringify(rows, null, 1));
  if (problems.length) {
    console.error(`PROBLEMS:\n${problems.join("\n")}`);
    process.exit(1);
  }

  const keys = Object.keys(out).sort();
  const body = `${HEADER.trim()}
export const SPREAD_REVIEW_DATES: Record<string, string> = {
${keys.map((k) => `  "${k}": "${out[k]}",`).join("\n")}
};
`;
  if (!DRY) writeFileSync(path.join(ROOT, OUT), body);
  console.log(
    DRY ? "dry run: nothing written" : `wrote ${OUT} (${keys.length} paths)`,
  );
}

await main();
